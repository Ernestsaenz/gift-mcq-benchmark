print("N4. LATENT-ABILITY MODEL: fit the per-cell response variability from the table")
print("   theta_i ~ Normal(mu, sigma);  p_i = logistic(theta_i)   [condition A]")
print("                                 q_i = logistic(theta_i - delta)  [condition B]")
print("   Responses in A and B are independent Bernoulli draws.  sigma controls how")
print("   many cells sit near p=0.5, i.e. how much pure re-run noise there is; delta is")
print("   the systematic effect of the manipulation.  Three parameters, three free cells")
print("   of the 2x2 -> exactly identified.")
Aacc = (n11 + n10) / N
Bacc = (n11 + n01) / N

GRID = [(-14 + 28 * i / 2400) for i in range(2401)]           # theta grid
def moments(mu, sigma, delta):
    h = GRID[1] - GRID[0]
    E = dict(p=0.0, pq=0.0, p1q=0.0, q1p=0.0, pp=0.0, w=0.0)
    for t in GRID:
        w = math.exp(-0.5 * ((t - mu) / sigma) ** 2) / (sigma * math.sqrt(2 * math.pi)) * h
        p = 1 / (1 + math.exp(-t))
        q = 1 / (1 + math.exp(-(t - delta)))
        E["w"] += w; E["p"] += w * p; E["pq"] += w * p * q
        E["p1q"] += w * p * (1 - q); E["q1p"] += w * (1 - p) * q
        E["pp"] += w * p * (1 - p)
    for k in E:
        if k != "w": E[k] /= E["w"]
    return E

def loss(par):
    mu, ls, delta = par
    sigma = math.exp(ls)
    E = moments(mu, sigma, delta)
    return ((E["pq"] - n11 / N) ** 2 + (E["p1q"] - n10 / N) ** 2 + (E["q1p"] - n01 / N) ** 2)

# Nelder-Mead
def nelder_mead(f, x0, step=0.4, it=600):
    n = len(x0)
    S = [list(x0)] + [[x0[j] + (step if j == i else 0) for j in range(n)] for i in range(n)]
    F = [f(s) for s in S]
    for _ in range(it):
        o = sorted(range(n + 1), key=lambda i: F[i]); S = [S[i] for i in o]; F = [F[i] for i in o]
        c = [sum(S[i][j] for i in range(n)) / n for j in range(n)]
        xr = [c[j] + 1.0 * (c[j] - S[n][j]) for j in range(n)]; fr = f(xr)
        if fr < F[0]:
            xe = [c[j] + 2.0 * (c[j] - S[n][j]) for j in range(n)]; fe = f(xe)
            S[n], F[n] = (xe, fe) if fe < fr else (xr, fr)
        elif fr < F[n - 1]:
            S[n], F[n] = xr, fr
        else:
            xc = [c[j] + 0.5 * (S[n][j] - c[j]) for j in range(n)]; fc = f(xc)
            if fc < F[n]: S[n], F[n] = xc, fc
            else:
                for i in range(1, n + 1):
                    S[i] = [(S[i][j] + S[0][j]) / 2 for j in range(n)]; F[i] = f(S[i])
    return S[0], F[0]

par, fv = nelder_mead(loss, [2.2, math.log(2.0), 1.2])
mu, sigma, delta = par[0], math.exp(par[1]), par[2]
E = moments(mu, sigma, delta)
print(f"   fitted mu={mu:.3f}  sigma={sigma:.3f}  delta={delta:.3f}   (residual {fv:.2e})")
print(f"   fitted cell probs: A+B+ {E['pq']:.4f} (obs {n11/N:.4f})  lost {E['p1q']:.4f} "
      f"(obs {n10/N:.4f})  gained {E['q1p']:.4f} (obs {n01/N:.4f})")
print(f"   implied instability mass S = N*E[p(1-p)] = {N*E['pp']:.1f} cells")
print(f"   implied re-run disagreement on an identical prompt = 2*E[p(1-p)] = {2*E['pp']:.3f}")
print(f"   NOISE-ONLY expected losses (set delta=0) = {N*E['pp']:.1f} of the {n10} observed "
      f"= {N*E['pp']/n10:.1%}")
print(f"   delta = {delta:.2f} logits = an odds ratio of {math.exp(-delta):.3f} on being correct.")

print()
print("   profile over sigma (sigma fixed; mu, delta refitted to A and B accuracy):")
print(f"   {'sigma':>7}{'delta':>8}{'2E[p(1-p)]':>13}{'E[lost]':>10}{'E[gained]':>11}"
      f"{'noise-only lost':>17}{'share of 247':>14}")
def fit_given_sigma(sig):
    def g(par):
        mu, delta = par
        E = moments(mu, sig, delta)
        return (E["p"] - Aacc) ** 2 + ((E["pq"] + E["q1p"]) - Bacc) ** 2
    p2_, _ = nelder_mead(g, [2.2, 1.2], step=0.3, it=400)
    return p2_[0], p2_[1]
for sig in (0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0):
    mu2, d2 = fit_given_sigma(sig)
    E2 = moments(mu2, sig, d2)
    print(f"   {sig:>7.1f}{d2:>8.2f}{2*E2['pp']:>13.3f}{N*E2['p1q']:>10.1f}{N*E2['q1p']:>11.1f}"
          f"{N*E2['pp']:>17.1f}{N*E2['pp']/n10:>13.1%}")
print(f"   -> only sigma near {sigma:.1f} reproduces the observed {n01} gains; larger sigma")
print("      (more noise) over-predicts gains, smaller sigma under-predicts them.")

